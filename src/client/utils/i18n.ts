/**
 * Dynamically loads the matching i18n translation bundle (e.g. es.json, ja.json)
 */
export async function loadTranslationBundle(lang: string): Promise<Record<string, string>> {
  const existing = translations[lang as SupportedLanguage];
  if (existing) {
    return existing;
  }
  try {
    const bundle = await import(`../locales/${lang}.json`);
    const loaded = bundle.default || bundle;
    translations[lang as SupportedLanguage] = loaded;
    return loaded;
  } catch (err) {
    console.warn(`Failed to dynamically load bundle for ${lang}:`, err);
    return (translations.en || {}) as Record<string, string>;
  }
}
