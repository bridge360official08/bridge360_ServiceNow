const allCodes = [
  'en', 'es', 'fr', 'de', 'pt-BR', 'ja', 'ko', 'it', 'nl', 'sv',
  'da', 'no', 'fi', 'pl', 'ru', 'tr', 'ar', 'he', 'th', 'vi',
  'id', 'ms', 'zh-CN', 'zh-TW', 'uk'
];

async function main() {
  const i18nPath = path.resolve('src/client/utils/i18n.ts');
  const localesDir = path.resolve('src/client/locales');
  
  // Read existing translations from i18n.ts
  const i18nModule = await import(`file://${i18nPath}`);
  const existingTrans = i18nModule.translations || {};

  for (const code of allCodes) {
    const bundle = {};
    const existing = existingTrans[code] || {};
    const specific = dicts[code] || {};

    // Fill all keys from baseEn or existing
    const baseSource = existingTrans.en || baseEn;
    for (const key of Object.keys(baseSource)) {
      bundle[key] = specific[key] || existing[key] || baseSource[key];
    }

    const outPath = path.join(localesDir, `${code}.json`);
    fs.writeFileSync(outPath, JSON.stringify(bundle, null, 2), 'utf8');
    console.log(`Generated ${code}.json (${Object.keys(bundle).length} keys)`);
  }
  console.log('All 25 locale files generated successfully.');
}

main().catch(console.error);
